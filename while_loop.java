package com.tka.control_1;

public class while_loop {
	public static void main(String[] args) {
		int k=1;
		while(k<=10) {
			System.out.print(k+" ");
			k++;
		}
		System.out.println();
		int k2=20;
		while(k2>=11) {
			System.out.print(k2+" ");
			k2--;
		}
		System.out.println();
		int k3=50;
		while(k3>=1) {
			System.out.print(k3+" ");
			k3-=4;
		}
		System.out.println();
		int k4=0;
		while(k4<=40) {
			System.out.print(k4+" ");
			k4+=4;
		}
	}
}
