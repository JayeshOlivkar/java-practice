package com.tka.control_1;


public class for_loop {
	public static void main(String[] args) {
		for(int i=1;i<=10;i++){
			System.out.print(i+" ");
		}
		System.out.println();
		for(int i=20;i>=11;i--) {
			System.out.print(i+" ");
		}
		System.out.println();
		for(int i=-10;i<=50;i+=5) {
			System.out.print(i+" ");
		}
		System.out.println();
		for(int i=50;i>=1;i-=5){
			System.out.print(i+" ");
		}
	}
}
