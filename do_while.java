package com.tka.control_1;

public class do_while {
	public static void main(String[] args) {
		int k=1;
		do {
			System.out.print(k+" ");
			k++;
		}while(k<=10);
		System.out.println();
		int j=100;
		do {
			System.out.print(j+" ");
			j+=4;
		}while(j<=150);
		System.out.println();
		int l=20;
		do {
			System.out.print(l+" ");
			l--;
		}while(l>=11);
		System.out.println();
		int i=50;
		do {
			System.out.print(i+" ");
			i-=3;
		}while(i>=1);
	}
}
